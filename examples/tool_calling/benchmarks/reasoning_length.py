def execute_tool(name: str, args: dict) -> str:
    """Execute a tool and return the result."""
    if name == "get_price":
        product = args.get("product", "").lower()
        return str(PRICES.get(product, "Not found"))
    elif name == "calculator":
        expr = args.get("expression", "")
        try:
            result = eval(expr, {"__builtins__": {}}, {})
            return str(result)
        except Exception as e:
            return f"Error: {e}"
    return "Unknown tool"


def call_api(
    model_id: str,
    messages: list[dict],
    provider: str,
    extra_params: dict | None = None,
    tools: list[dict] | None = None,
    temperature: float = DEFAULT_TEMPERATURE,
    top_p: float = DEFAULT_TOP_P,
    timeout: int = DEFAULT_TIMEOUT,
    max_retries: int = 1,
) -> dict:
    """Call the OpenRouter API with retry on failure."""
    headers = {"Authorization": f"Bearer {API_KEY}", "Content-Type": "application/json"}

    payload = {
        "model": model_id,
        "messages": messages,
        "temperature": temperature,
        "top_p": top_p,
        "provider": {"order": [provider]},
    }

    if tools:
        payload["tools"] = tools

    if extra_params:
        payload.update(extra_params)

    last_error = None
    for attempt in range(max_retries + 1):
        try:
            response = requests.post(CHAT_URL, headers=headers, json=payload, timeout=timeout)
            result = response.json()
            # Retry on API error (rate limit, server error, etc.)
            if "error" in result and attempt < max_retries:
                last_error = result
                time.sleep(2)  # Wait before retry
                continue
            return result
        except requests.exceptions.Timeout:
            last_error = {"error": {"message": "Request timed out"}}
            if attempt < max_retries:
                time.sleep(2)
                continue
        except Exception as e:
            last_error = {"error": {"message": str(e)}}
            if attempt < max_retries:
                time.sleep(2)
                continue

    return last_error


@dataclass
class LengthMetrics:
    """Length metrics for a single response (in tokens)."""

    reasoning: int  # reasoning/thinking token count
    content: int  # actual response token count
    total: int  # reasoning + content

    @classmethod
    def from_response(cls, response: dict, hf_model_id: str) -> "LengthMetrics | None":
        """Extract token length metrics from API response."""
        if "error" in response:
            return None
        try:
            msg = response["choices"][0]["message"]
            reasoning_text = msg.get("reasoning", "") or ""
            content_text = msg.get("content", "") or ""
            reasoning = count_tokens(reasoning_text, hf_model_id)
            content = count_tokens(content_text, hf_model_id)
            return cls(reasoning=reasoning, content=content, total=reasoning + content)
        except (KeyError, IndexError):
            return None


def get_reasoning_length(response: dict, hf_model_id: str) -> int | None:
    """Extract reasoning token length from API response (legacy)."""
    metrics = LengthMetrics.from_response(response, hf_model_id)
    return metrics.reasoning if metrics else None


def calculate_stats(values: list[int]) -> dict[str, float]:
    """Calculate statistics for a list of values."""
    if not values:
        return {"avg": 0, "median": 0, "std": 0, "cv": 0, "min": 0, "max": 0}

    avg = statistics.mean(values)
    median = statistics.median(values)
    std = statistics.stdev(values) if len(values) > 1 else 0
    cv = (std / avg * 100) if avg > 0 else 0

    return {
        "avg": avg,
        "median": median,
        "std": std,
        "cv": cv,
        "min": min(values),
        "max": max(values),
    }


