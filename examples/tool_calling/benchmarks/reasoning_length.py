@dataclass
class TurnMetrics:
    """Metrics for a single turn in multi-turn conversation."""

    name: str  # turn name: greeting, price_req, calc_req, final
    reasoning: int
    content: int
    total: int


def run_multi_turn_test(
    config: ModelConfig,
    iterations: int = 5,
    temperature: float = DEFAULT_TEMPERATURE,
    top_p: float = DEFAULT_TOP_P,
    verbose: bool = True,
) -> dict[str, Any]:
    """Run multi-turn reasoning length test."""

    def extract_metrics(msg: dict) -> tuple[int, int, int]:
        """Extract reasoning, content, total token counts from message."""
        reasoning_text = msg.get("reasoning", "") or ""
        content_text = msg.get("content", "") or ""
        reasoning = count_tokens(reasoning_text, config.hf_model_id)
        content = count_tokens(content_text, config.hf_model_id)
        return reasoning, content, reasoning + content

    def run_single_conversation() -> tuple[dict[str, int] | None, list[TurnMetrics]]:
        """Run a single multi-turn conversation and return totals + turn breakdown.

        Turn names:
        - greeting: Response to "Hello!"
        - price_req: get_price tool call(s) - may appear multiple times for sequential models
        - calc_req: calculator tool call
        - final: Final answer after all tools

        Returns:
            Tuple of (totals dict with reasoning/content/total, list of TurnMetrics)
        """
        messages = []
        full_messages = []  # For dump: includes reasoning
        total_reasoning = 0
        total_content = 0
        turns = []
        max_turns = 10  # Safety limit

        # Turn 1: Greeting
        messages.append({"role": "user", "content": "Hello!"})
        full_messages.append({"role": "user", "content": "Hello!"})
        response = call_api(
            model_id=config.model_id,
            messages=messages,
            provider=config.provider,
            extra_params=config.extra_params,
            temperature=temperature,
            top_p=top_p,
        )

        if "error" in response:
            return None, [TurnMetrics("greeting", -1, -1, -1)], full_messages

        msg = response["choices"][0]["message"]
        r, c, t = extract_metrics(msg)
        total_reasoning += r
        total_content += c
        turns.append(TurnMetrics("greeting", r, c, t))
        messages.append({"role": "assistant", "content": msg.get("content", "")})
        full_messages.append(msg)  # Full response with reasoning

        # Turn 2+: Tool requests
        user_msg = {
            "role": "user",
            "content": "Get the prices of apple and banana, then calculate the average price using the calculator tool.",
        }
        messages.append(user_msg)
        full_messages.append(user_msg)

        # Loop to handle both parallel and sequential tool calls
        turn_count = 0
        while turn_count < max_turns:
            turn_count += 1

            response = call_api(
                model_id=config.model_id,
                messages=messages,
                provider=config.provider,
                extra_params=config.extra_params,
                tools=TOOLS,
                temperature=temperature,
                top_p=top_p,
            )

            if "error" in response:
                return None, turns + [TurnMetrics("error", -1, -1, -1)], full_messages

            msg = response["choices"][0]["message"]
            r, c, t = extract_metrics(msg)
            total_reasoning += r
            total_content += c
            tool_calls = msg.get("tool_calls", [])

            if not tool_calls:
                # No more tool calls - this is the final answer
                turns.append(TurnMetrics("final", r, c, t))
                full_messages.append(msg)
                break

            # Determine turn type based on tool being called
            tool_names = [tc["function"]["name"] for tc in tool_calls]
            if "calculator" in tool_names:
                turn_type = "calc_req"
            else:
                turn_type = "price_req"

            turns.append(TurnMetrics(turn_type, r, c, t))

            # Execute tools
            messages.append({"role": "assistant", "content": msg.get("content", ""), "tool_calls": tool_calls})
            full_messages.append(msg)

            for tc in tool_calls:
                args = tc["function"]["arguments"]
                if isinstance(args, str):
                    args = json.loads(args)
                result = execute_tool(tc["function"]["name"], args)
                tool_msg = {"role": "tool", "tool_call_id": tc["id"], "content": result}
                messages.append(tool_msg)
                full_messages.append(tool_msg)

            # If calculator was called, next response should be final
            if turn_type == "calc_req":
                response = call_api(
                    model_id=config.model_id,
                    messages=messages,
                    provider=config.provider,
                    extra_params=config.extra_params,
                    temperature=temperature,
                    top_p=top_p,
                )

                if "error" in response:
                    return None, turns + [TurnMetrics("final", -1, -1, -1)], full_messages

                msg = response["choices"][0]["message"]
                r, c, t = extract_metrics(msg)
                total_reasoning += r
                total_content += c
                turns.append(TurnMetrics("final", r, c, t))
                full_messages.append(msg)
                break

        totals = {
            "reasoning": total_reasoning,
            "content": total_content,
            "total": total_reasoning + total_content,
        }
        return totals, turns, full_messages

    reasoning_values = []
    content_values = []
    total_values = []
    all_turns = []
    last_messages = None
    errors = 0

    if verbose:
        print(f"\n[{config.name}] Multi-turn test ({iterations} iterations)")

    for i in range(iterations):
        totals, turns, conv_messages = run_single_conversation()
        if totals is not None:
            last_messages = conv_messages
            reasoning_values.append(totals["reasoning"])
            content_values.append(totals["content"])
            total_values.append(totals["total"])
            all_turns.append(turns)
            turn_str = " → ".join([f"{t.name}:{t.reasoning}" for t in turns])
            if verbose:
                print(
                    f"  #{i + 1}: r={totals['reasoning']:,} c={totals['content']:,} t={totals['total']:,} ({turn_str})"
                )
        else:
            errors += 1
            if verbose:
                print(f"  #{i + 1}: ERROR")

        time.sleep(config.request_delay)

    reasoning_stats = calculate_stats(reasoning_values)
    content_stats = calculate_stats(content_values)
    total_stats = calculate_stats(total_values)

    # Calculate turn count stats (useful for detecting parallel vs sequential tool calls)
    turn_counts = [len(t) for t in all_turns]
    turn_count_stats = calculate_stats(turn_counts) if turn_counts else {}

    # Calculate accuracy: correct flow requires price_req before calc_req
    def is_correct_flow(turns: list[TurnMetrics]) -> bool:
        turn_names = [t.name for t in turns]
        # Must have at least one price_req before calc_req
        if "calc_req" in turn_names and "price_req" in turn_names:
            calc_idx = turn_names.index("calc_req")
            price_idx = turn_names.index("price_req")
            return price_idx < calc_idx
        # If no calc_req but has price_req and final, could be valid (model calculated mentally)
        if "price_req" in turn_names and "final" in turn_names:
            return True
        return False

    correct_count = sum(1 for t in all_turns if is_correct_flow(t))
    accuracy = (correct_count / len(all_turns) * 100) if all_turns else 0

    if verbose and reasoning_values:
        cv_marker = "✅" if reasoning_stats["cv"] < 40 else ("⚠️" if reasoning_stats["cv"] < 60 else "❌")
        acc_marker = "✅" if accuracy >= 90 else ("⚠️" if accuracy >= 70 else "❌")
        avg_turns = turn_count_stats.get("avg", 0)
        print(f"  → reasoning: avg={reasoning_stats['avg']:,.0f} CV={reasoning_stats['cv']:.0f}% {cv_marker}")
        print(f"  → content:   avg={content_stats['avg']:,.0f} CV={content_stats['cv']:.0f}%")
        print(f"  → total:     avg={total_stats['avg']:,.0f} CV={total_stats['cv']:.0f}%")
        print(f"  → turns={avg_turns:.1f} acc={accuracy:.0f}% {acc_marker}")

    # Convert TurnMetrics to serializable format
    turns_serializable = [[[t.name, t.reasoning, t.content, t.total] for t in conv_turns] for conv_turns in all_turns]

    # Save last conversation messages
    if last_messages:
        save_messages_dump(last_messages, config.name, config.hf_model_id, "multi")

    return {
        "config": config.name,
        "mode": "multi-turn",
        "iterations": iterations,
        "successful": len(reasoning_values),
        "errors": errors,
        "correct": correct_count,
        "accuracy": accuracy,
        "reasoning_values": reasoning_values,
        "content_values": content_values,
        "total_values": total_values,
        "reasoning_stats": reasoning_stats,
        "content_stats": content_stats,
        "total_stats": total_stats,
        "turns": turns_serializable,
        "turn_counts": turn_counts,
        "turn_count_stats": turn_count_stats,
        # Legacy compatibility
        "values": reasoning_values,
        "stats": reasoning_stats,
        "turn_stats": turn_count_stats,
    }


