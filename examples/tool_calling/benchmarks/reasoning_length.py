# Tokenizer cache
@lru_cache(maxsize=16)
def get_tokenizer(hf_model_id: str):
    """Get cached tokenizer for a model."""
    from transformers import AutoTokenizer

    return AutoTokenizer.from_pretrained(hf_model_id, trust_remote_code=True)


def count_tokens(text: str, hf_model_id: str) -> int:
    """Count tokens in text using the model's tokenizer."""
    if not text:
        return 0
    tokenizer = get_tokenizer(hf_model_id)
    return len(tokenizer.encode(text, add_special_tokens=False))


